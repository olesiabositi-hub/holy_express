export function tutorial(parent: HTMLElement, onDone: () => void) {
  const bg = el("div", "htp-bg");
  const box = el("div", "tut");
  bg.appendChild(box);
  parent.appendChild(bg);
  let i = 0;
  const close = () => {
    bg.remove();
    onDone();
  };
  const render = () => {
    const s = STEPS[i];
    box.innerHTML = `<div class="tut-top"><span>${String(i + 1).padStart(2, "0")} / ${String(STEPS.length).padStart(2, "0")}</span><button class="tut-x" aria-label="Закрыть">✕</button></div>
      <div class="tut-ic">${s.ic}</div><h3>${s.t}</h3><p>${s.p}</p>${s.fig ?? ""}
      <div class="tut-nav"><button class="tut-skip">Пропустить</button><div class="dots">${STEPS.map((_, k) => `<i class="${k === i ? "on" : ""}"></i>`).join("")}</div>
      <div>${i ? `<button class="btn tut-back">Назад</button>` : ""}<button class="btn primary tut-next">${i === STEPS.length - 1 ? "Начать" : "Дальше"}</button></div></div>`;
    box.querySelector<HTMLButtonElement>(".tut-x")!.onclick = close;
    box.querySelector<HTMLButtonElement>(".tut-skip")!.onclick = close;
    box.querySelector<HTMLButtonElement>(".tut-back")?.addEventListener("click", () => {
      i--;
      render();
    });
    box.querySelector<HTMLButtonElement>(".tut-next")!.onclick = () => {
      if (i === STEPS.length - 1) return close();
      i++;
      render();
    };
  };
  render();
}

