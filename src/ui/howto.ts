export function howToPlay(parent: HTMLElement) {
  const bg = el("div", "htp-bg");
  const box = el("div", "htp");
  bg.appendChild(box);
  parent.appendChild(bg);
  const tabs = ["Правила", "Слова в уликах", "Приёмы", "Вопросы"];
  let tab = 0;
  const close = () => bg.remove();
  bg.addEventListener("click", (e) => e.target === bg && close());
  const body = () => {
    if (tab === 0)
      return `<h4>Цель</h4><p>Расставь всех персонажей и улику на плане. Виновный — единственный подозреваемый в одной зоне с уликой.</p>
        <h4>Правила</h4><ul><li>В каждом ряду и каждом столбце — ровно один.</li><li>На занятые клетки (стол, стеллаж, плита — со штриховкой) встать нельзя.</li><li>У каждого есть улика-показание. Все улики правдивы.</li></ul>
        <h4>Управление</h4><ul><li><b>Нажми на персонажа</b> — выбрать его.</li><li><b>Короткое нажатие на клетку</b> — заметка (маленькая буква).</li><li><b>Нажми и подержи клетку</b> — поставить персонажа (большая фишка).</li><li><b>Проведи по клеткам</b> — заметки на несколько клеток.</li><li>На компьютере персонажа можно перетащить из карточки на поле.</li></ul>
        <h4>Инструменты</h4><ul><li><b>✕ Крестики</b> — отмечай клетки, где точно никого нет.</li><li><b>Ластик</b> — стереть клетку. Удержи кнопку — стереть всё.</li><li><b>Отменить</b> — шаг назад (или Ctrl+Z).</li><li><b>Подсказка</b> — объясняет решение по шагам.</li><li><b>Проверить</b> — когда все стоят на местах.</li></ul>`;
    if (tab === 1) return `<dl class="kw">${KEYWORDS.map(([k, v]) => `<dt>${k}</dt><dd>${v}</dd>`).join("")}</dl>`;
    if (tab === 2)
      return `<h4>1. Ищи ряды и столбцы с одной свободной клеткой</h4><p>В каждом ряду кто-то стоит. Если в ряду осталась одна клетка, где можно встать, — там точно кто-то есть, даже если пока непонятно кто.</p>${mini(["#.##", "....", "....", "...."], "в верхнем ряду свободна одна клетка")}
        <h4>2. Следи за «занятыми» рядами</h4><p>Если двое точно делят между собой два ряда (неважно, кто в каком), — остальным в эти ряды нельзя.</p>${mini(["аа..", "бб..", "xxв.", "xx.в"], "А и Б заняли два ряда — В идёт ниже")}
        <h4>3. Вычёркивай пересечения</h4><p>Если персонаж может стоять только в двух клетках, никто не может стоять там, где обе эти клетки «видны» по ряду и столбцу сразу.</p>${mini(["а.x.", "....", "x.а.", "...."], "А в одной из двух клеток — крестики можно ставить")}`;
    return `<h4>Сохраняется ли прогресс?</h4><p>Да, в этом браузере: расстановка, заметки, время и подсказки.</p>
      <h4>Сколько решений у дела?</h4><p>Ровно одно, и его можно найти логикой, без угадывания.</p>
      <h4>Подсказки штрафуют?</h4><p>Нет, просто считаются — число появится на билете в финале.</p>
      <h4>Что за билет?</h4><p>Каждое раскрытое дело — часть билета «Код-фриз экспресса». Собери все пять — в финале билет станет целым, а на нём будет код с подарком.</p>
      <h4>Вагон закрыт?</h4><p>Каждый день с 21 по 25 декабря открывается новый. Пропущенные дела не сгорают.</p>`;
  };
  const render = () => {
    box.innerHTML = `<div class="htp-head"><h3>Как играть</h3><button class="tut-x" aria-label="Закрыть">✕</button></div>
      <div class="htp-tabs" role="tablist">${tabs.map((t, i) => `<button role="tab" aria-selected="${i === tab}" data-i="${i}">${t}</button>`).join("")}</div>
      <div class="htp-body">${body()}</div>`;
    box.querySelector<HTMLButtonElement>(".tut-x")!.onclick = close;
    box.querySelectorAll<HTMLButtonElement>(".htp-tabs button").forEach((b) => (b.onclick = () => {
      tab = Number(b.dataset.i);
      render();
    }));
  };
  render();
}
